/// Positional placeholders {0}, {1}, ... are replaced by [args].
String tr(String lang, String key, [List<Object?> args = const []]) {
  var s = _strings[lang]?[key] ?? _strings['en']![key] ?? key;
  for (var i = 0; i < args.length; i++) {
    s = s.replaceAll('{$i}', '${args[i]}');
  }
  return s;
}
